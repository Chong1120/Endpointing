-- Creates an organization + profile for a Supabase Auth user on first use.
create or replace function public.ensure_user_profile(p_user_id uuid, p_email text, p_org_name text)
returns table (user_id uuid, organization_id uuid, email text, role text, organization_name text)
language plpgsql
set search_path = public
as $$
#variable_conflict use_column
declare
  v_org uuid;
begin
  perform pg_advisory_xact_lock(hashtextextended(p_user_id::text, 0));

  if not exists (select 1 from public.users u where u.id = p_user_id) then
    insert into public.organizations (name)
      values (coalesce(nullif(trim(p_org_name), ''), 'My Organization'))
      returning id into v_org;
    insert into public.users (id, organization_id, email, role)
      values (p_user_id, v_org, p_email, 'admin');
  end if;

  return query
    select u.id, u.organization_id, u.email, u.role, o.name
    from public.users u
    join public.organizations o on o.id = u.organization_id
    where u.id = p_user_id;
end;
$$;

-- Full-text search across an organization's SAFE archive, with highlighted
-- snippets from the redacted transcript.
create or replace function public.search_calls(
  p_org        uuid,
  p_query      text,
  p_status     text default null,
  p_department text default null,
  p_sentiment  text default null,
  p_pii_type   text default null,
  p_from       timestamptz default null,
  p_to         timestamptz default null,
  p_limit      integer default 25,
  p_offset     integer default 0
)
returns table (
  id                uuid,
  call_number       bigint,
  original_filename text,
  department        text,
  status            text,
  sentiment         text,
  topics            text[],
  pii_total         integer,
  pii_types         text[],
  duration_seconds  numeric,
  created_at        timestamptz,
  processed_at      timestamptz,
  summary           text,
  snippet           text,
  rank              real,
  total_count       bigint
)
language sql
stable
set search_path = public
as $$
  with q as (
    select websearch_to_tsquery('english', p_query) as tsq
  ),
  matched as (
    select c.*, ts_rank_cd(c.search_vector, q.tsq) as rnk, q.tsq as tsq
    from public.calls c, q
    where c.organization_id = p_org
      and c.search_vector @@ q.tsq
      and (p_status is null or c.status = p_status)
      and (p_department is null or c.department = p_department)
      and (p_sentiment is null or c.sentiment = p_sentiment)
      and (p_pii_type is null or c.pii_types @> array[p_pii_type])
      and (p_from is null or c.created_at >= p_from)
      and (p_to is null or c.created_at < p_to)
  )
  select
    m.id, m.call_number, m.original_filename, m.department, m.status, m.sentiment, m.topics,
    m.pii_total, m.pii_types, m.duration_seconds, m.created_at, m.processed_at,
    m.ai_summary ->> 'summary',
    ts_headline('english', coalesce(m.redacted_transcript, ''), m.tsq,
      'StartSel=⟦, StopSel=⟧, MaxFragments=2, MaxWords=22, MinWords=8, FragmentDelimiter=" … "'),
    m.rnk,
    count(*) over ()
  from matched m
  order by m.rnk desc, m.created_at desc
  limit greatest(1, least(p_limit, 100))
  offset greatest(0, p_offset);
$$;

-- ---------------------------------------------------------------------------
-- Row level security & privileges
-- ---------------------------------------------------------------------------

alter table public.organizations       enable row level security;
alter table public.users               enable row level security;
alter table public.calls               enable row level security;
alter table public.call_utterances     enable row level security;
alter table public.audit_logs          enable row level security;
alter table public.pii_policy_settings enable row level security;

revoke all on public.organizations, public.users, public.calls, public.call_utterances,
              public.audit_logs, public.pii_policy_settings
  from anon, authenticated;

grant all on public.organizations, public.users, public.calls, public.call_utterances,
             public.audit_logs, public.pii_policy_settings
  to service_role;
grant usage, select on all sequences in schema public to service_role;

revoke all on function public.ensure_user_profile(uuid, text, text) from public, anon, authenticated;
grant execute on function public.ensure_user_profile(uuid, text, text) to service_role;

revoke all on function public.search_calls(uuid, text, text, text, text, text, timestamptz, timestamptz, integer, integer)
  from public, anon, authenticated;
grant execute on function public.search_calls(uuid, text, text, text, text, text, timestamptz, timestamptz, integer, integer)
  to service_role;

