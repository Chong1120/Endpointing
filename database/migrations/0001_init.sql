-- SafeCall schema
--
-- The permanent archive stores ONLY privacy-safe artifacts: redacted
-- transcripts, redacted speaker utterances, PII statistics (counts, never
-- values), AI analysis produced from the redacted text, call metadata and
-- audit records. Raw audio and unredacted transcripts are never written here.
--
-- Access model: the browser never queries these tables. All reads/writes go
-- through the SafeCall API using the service role, which scopes every query to
-- the caller's organization. RLS is enabled with no policies so the anon and
-- authenticated roles are denied by default (defense in depth).

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------------
-- Organizations & users
-- ---------------------------------------------------------------------------

create table if not exists public.organizations (
  id          uuid primary key default gen_random_uuid(),
  name        text not null,
  created_at  timestamptz not null default now()
);

create table if not exists public.users (
  id               uuid primary key references auth.users (id) on delete cascade,
  organization_id  uuid not null references public.organizations (id) on delete cascade,
  email            text not null,
  role             text not null default 'admin' check (role in ('admin', 'analyst', 'viewer')),
  created_at       timestamptz not null default now()
);

create index if not exists users_organization_id_idx on public.users (organization_id);

-- ---------------------------------------------------------------------------
-- Calls (safe archive)
-- ---------------------------------------------------------------------------

create table if not exists public.calls (
  id                          uuid primary key default gen_random_uuid(),
  call_number                 bigint generated by default as identity (start with 1001) unique,
  organization_id             uuid not null references public.organizations (id) on delete cascade,
  created_by                  uuid references auth.users (id) on delete set null,
  original_filename           text not null,
  department                  text not null default 'Customer Support',
  source                      text not null default 'upload' check (source in ('upload', 'sample')),
  status                      text not null default 'UPLOADING'
                                check (status in ('UPLOADING', 'TRANSCRIBING', 'PROCESSING', 'COMPLETED', 'FAILED')),
  failed_stage                text,
  error_message               text,
  policy_preset               text not null
                                check (policy_preset in ('CONTACT_CENTER', 'FINANCIAL', 'HEALTHCARE', 'CUSTOM')),
  pii_policies                text[] not null default '{}',
  analysis_enabled            boolean not null default true,
  detected_language           text,
  duration_seconds            numeric(10, 2),
  speakers_count              integer,
  speech_model_used           text,
  assemblyai_transcript_id    text unique,
  safe_audio_path             text,
  safe_audio_format           text check (safe_audio_format in ('mp3', 'wav')),
  redacted_transcript         text,
  pii_counts                  jsonb not null default '{}'::jsonb,
  pii_total                   integer not null default 0,
  pii_types                   text[] not null default '{}',
  ai_summary                  jsonb,
  sentiment                   text check (sentiment in ('positive', 'neutral', 'negative')),
  topics                      text[] not null default '{}',
  created_at                  timestamptz not null default now(),
  submitted_at                timestamptz,
  transcription_completed_at  timestamptz,
  processed_at                timestamptz,
  original_deleted_at         timestamptz,
  updated_at                  timestamptz not null default now(),
  -- Full-text search over SAFE data only (redacted transcript + AI analysis + metadata).
  search_vector tsvector generated always as (
    setweight(jsonb_to_tsvector('english', coalesce(ai_summary, '{}'::jsonb), '["string"]'), 'A') ||
    setweight(to_tsvector('english', coalesce(redacted_transcript, '')), 'B') ||
    setweight(to_tsvector('english', coalesce(department, '')), 'C') ||
    setweight(to_tsvector('english', coalesce(original_filename, '')), 'D')
  ) stored
);

create index if not exists calls_org_created_idx     on public.calls (organization_id, created_at desc);
create index if not exists calls_org_status_idx      on public.calls (organization_id, status);
create index if not exists calls_status_idx          on public.calls (status);
create index if not exists calls_created_at_idx      on public.calls (created_at desc);
create index if not exists calls_org_department_idx  on public.calls (organization_id, department);
create index if not exists calls_org_sentiment_idx   on public.calls (organization_id, sentiment);
create index if not exists calls_search_idx          on public.calls using gin (search_vector);
create index if not exists calls_pii_types_idx       on public.calls using gin (pii_types);
create index if not exists calls_topics_idx          on public.calls using gin (topics);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists calls_set_updated_at on public.calls;
create trigger calls_set_updated_at
  before update on public.calls
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------
-- Speaker-separated REDACTED utterances
-- ---------------------------------------------------------------------------

create table if not exists public.call_utterances (
  id        uuid primary key default gen_random_uuid(),
  call_id   uuid not null references public.calls (id) on delete cascade,
  seq       integer not null,
  speaker   text not null,
  start_ms  integer not null,
  end_ms    integer not null,
  text      text not null,
  unique (call_id, seq)
);

-- ---------------------------------------------------------------------------
-- Audit trail (technical IDs and counts only — never raw PII)
-- ---------------------------------------------------------------------------

create table if not exists public.audit_logs (
  id               bigint generated always as identity primary key,
  organization_id  uuid not null references public.organizations (id) on delete cascade,
  call_id          uuid references public.calls (id) on delete set null,
  event_type       text not null,
  metadata         jsonb not null default '{}'::jsonb,
  actor_id         uuid,
  created_at       timestamptz not null default clock_timestamp()
);

create index if not exists audit_logs_org_created_idx on public.audit_logs (organization_id, created_at desc);
create index if not exists audit_logs_call_idx        on public.audit_logs (call_id, created_at);
create index if not exists audit_logs_event_type_idx  on public.audit_logs (organization_id, event_type);

-- ---------------------------------------------------------------------------
-- Per-organization overrides for the PII policy presets
-- ---------------------------------------------------------------------------

create table if not exists public.pii_policy_settings (
  organization_id  uuid not null references public.organizations (id) on delete cascade,
  preset           text not null check (preset in ('CONTACT_CENTER', 'FINANCIAL', 'HEALTHCARE', 'CUSTOM')),
  policies         text[] not null,
  updated_by       uuid,
  updated_at       timestamptz not null default now(),
  primary key (organization_id, preset)
);

